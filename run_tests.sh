#!/bin/bash

# Unit Test Runner for Student Check-in System
# This script runs all Go unit tests with coverage reporting

set -e

GREEN='\033[0;32m'
RED='\033[0;31m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo "╔══════════════════════════════════════════════════════════════╗"
echo "║          Go Unit Tests - Student Check-in System            ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""

# Run validation tests
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${YELLOW}Running Validation Tests${NC}"
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo ""

if go test -v ./internal/validation/...; then
    echo -e "${GREEN}✓ Validation tests passed${NC}"
else
    echo -e "${RED}✗ Validation tests failed${NC}"
    exit 1
fi

echo ""

# Run handler tests
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${YELLOW}Running Handler Tests${NC}"
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo ""

if go test -v ./internal/handlers/...; then
    echo -e "${GREEN}✓ Handler tests passed${NC}"
else
    echo -e "${RED}✗ Handler tests failed${NC}"
    exit 1
fi

echo ""

# Run all tests with coverage
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${YELLOW}Running All Tests with Coverage${NC}"
echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo ""

go test ./internal/... -coverprofile=coverage.out
go tool cover -func=coverage.out

echo ""
echo -e "${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${GREEN}All tests passed! ✓${NC}"
echo -e "${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo ""
echo "Coverage report saved to: coverage.out"
echo "To view HTML coverage report, run:"
echo "  go tool cover -html=coverage.out"
echo ""
